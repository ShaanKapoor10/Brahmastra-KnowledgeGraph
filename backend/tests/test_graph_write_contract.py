"""
Every write into the derived graph must be rebuildable from Postgres.

The graph is a cache (stores/base.DERIVED_DATA). A fact that only the graph
holds is lost the first time the graph is rebuilt -- which is how one meeting
record's 251 facts went missing from a 2026-10-13 rebuild, and how the
since-removed POST /graph/triples could have planted facts no note supports.

So the modules that may write derived graph data are listed here, each with
the reason a rebuild reproduces what it writes. A new writer fails this test
until it is added -- together with its regeneration path and a test that a
rebuild reproduces it (like tests/test_ingest_records.py).
"""
from __future__ import annotations

import re
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
WRITES = re.compile(r"\.(insert_triples|delete_triples_for_note|replace_canonical_map|save_graph|"
                    r"save_cluster_summaries|clear_derived)\(")

ALLOWED = {
    "brahmastra/db.py": "the facade itself",
    "brahmastra/stores/neo4j_store.py": "a store implementing the contract",
    "brahmastra/stores/sqlite_store.py": "a store implementing the contract",
    "brahmastra/stores/composite_store.py": "a store implementing the contract",
    "brahmastra/extraction.py": "facts extracted from notes; a full rebuild re-extracts them",
    "brahmastra/entity_resolution.py": "a function of the extracted facts",
    "brahmastra/concept_graph.py": "a function of the facts and the resolution",
    "brahmastra/ingest/assemble.py": "meeting records, regenerated by ingest/records.py",
    "brahmastra/ingest/records.py": "the regeneration of meeting records from Postgres",
    "brahmastra/migrate_to_neo4j.py": "copies one store's derived data into another",
}


def test_only_rebuildable_code_writes_the_graph():
    writers = set()
    for path in [*BACKEND.joinpath("brahmastra").rglob("*.py"), BACKEND / "main.py"]:
        if WRITES.search(path.read_text(encoding="utf-8")):
            writers.add(path.relative_to(BACKEND).as_posix())
    unexpected = sorted(writers - ALLOWED.keys())
    assert not unexpected, (
        f"{unexpected} write derived graph data. A rebuild only reproduces facts it can "
        "recompute from Postgres: add a regeneration path and a rebuild test, then list "
        "the module in ALLOWED with the reason.")


def test_the_api_cannot_write_facts_directly():
    import importlib

    import main
    importlib.reload(main)
    routes = {(m, p) for p, item in main.app.openapi()["paths"].items() for m in item}
    assert ("post", "/graph/triples") not in routes
